export function statusForError(errorOrCode, fallback = 400) {
  const code = String(errorOrCode?.message || errorOrCode || '').trim();
  if (!code) return fallback;
  if (STATUS_BY_CODE.has(code)) return STATUS_BY_CODE.get(code);
  if (code.endsWith('_NOT_FOUND')) return 404;
  if (code.endsWith('_REQUIRED') || code.startsWith('INVALID_') || code.startsWith('MISSING_')) return 400;
  if (code.includes('DENIED') || code.includes('FORBIDDEN')) return 403;
  if (code.includes('CONFLICT') || code.includes('ALREADY_')) return 409;
  return fallback;
}
